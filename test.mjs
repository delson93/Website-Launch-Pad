import {test} from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {once} from 'node:events';
test('independent invitations, owner isolation, countdown, QR, moderation and lifecycle',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'launchpad-'));
 const origin='http://127.0.0.1:35917';
 const server=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:'35917',PUBLIC_ORIGIN:origin,DATA_DIR:dir},stdio:['ignore','pipe','inherit']});
 t.after(async()=>{const ended=once(server,'exit');server.kill();await ended;await rm(dir,{recursive:true,force:true});});
 await Promise.race([once(server.stdout,'data'),once(server,'exit').then(()=>{throw Error('Server exited before listening');})]);
 const post=(path,data)=>fetch(new URL(path,origin),{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(data)});
 const config={url:'https://example.com/launch',template:'ribbon',title:'Opening day'};
 const a=await(await post('/api/create',config)).json(),b=await(await post('/api/create',config)).json();
 assert.notEqual(a.public,b.public);assert.notEqual(a.manage,b.manage);
 const publicHTML=await(await fetch(a.public)).text();assert.match(publicHTML,/Opening day/);assert.ok(!publicHTML.includes(a.manage.split('/').pop()));
 assert.equal((await post('/api/create',{...config,url:'javascript:alert(1)'})).status,400);
 assert.equal((await post('/manage/incorrect',config)).status,404);
 assert.equal((await post(a.manage,{...config,at:Date.now()+3600000,title:'Future launch'})).status,200);
 const id=a.public.split('/').pop(),go=origin+'/go/'+id;
 assert.equal((await fetch(go)).status,409);assert.equal((await post('/event/'+id+'/start',{})).status,409);
 assert.match(await(await fetch(b.public)).text(),/Opening day/);
 await post(a.manage,config);
 assert.equal((await post('/event/'+id+'/start',{})).status,200);
 assert.equal((await post('/event/'+id+'/finish',{})).status,200);
 assert.equal((await fetch(go,{redirect:'manual'})).headers.get('location'),config.url);
 const qr=await fetch(origin+'/qr/'+id);assert.equal(qr.headers.get('content-type'),'image/png');assert.equal(Buffer.from(await qr.arrayBuffer()).readUInt32BE(),0x89504e47);
 await post(a.manage+'/toggle',{});assert.equal((await fetch(a.public)).status,404);
 await post(a.manage+'/toggle',{});assert.equal((await fetch(a.public)).status,200);
 await post(a.manage+'/delete',{});assert.equal((await fetch(a.public)).status,404);assert.equal((await fetch(b.public)).status,200);
});
